<?php
/**
 * Regenerate database/schema.sql and database/spence_empty.db from the migrations.
 *
 *   LD_LIBRARY_PATH=/usr/lib/x86_64-linux-gnu php ops/rebuild-schema.php
 *
 * Applies the current schema.sql to a scratch database, runs get_db_connection()'s migrations on
 * it and writes the result back, so after adding a migration this brings both files up to date.
 * tests/test_schema.php fails while they lag behind.
 */
if (PHP_SAPI !== 'cli') exit(1);
require_once __DIR__ . '/../core/db_helper.php';

/** The migrated schema as SQL: tables in creation order, then their indexes. */
function dumpSpenceSchema(PDO $db): string {
    $rows = $db->query("SELECT type, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
        ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid")->fetchAll(PDO::FETCH_ASSOC);
    return implode("\n", array_map(fn($row) => $row['sql'] . ';', $rows)) . "\n";
}

/** Build a migrated database at $path from schema.sql. */
function buildSpenceDatabase(string $schemaFile, string $path): PDO {
    foreach (['', '-wal', '-shm'] as $suffix) @unlink($path . $suffix);
    (new PDO('sqlite:' . $path))->exec(file_get_contents($schemaFile));
    return get_db_connection($path);
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    $schemaFile = __DIR__ . '/../database/schema.sql';
    $emptyDb = __DIR__ . '/../database/spence_empty.db';
    $scratch = tempnam(sys_get_temp_dir(), 'spence-schema-');

    $db = buildSpenceDatabase($schemaFile, $scratch);
    $header = "-- SPENCE schema: a fresh database after every migration in core/db_helper.php.\n"
        . "-- Generated by ops/rebuild-schema.php; edit the migrations, not this file.\n";
    file_put_contents($schemaFile, $header . dumpSpenceSchema($db));

    // The template is a single self-contained file; get_db_connection() switches it to WAL on first use
    $db->exec('PRAGMA journal_mode = DELETE');
    $db->exec('VACUUM');
    $db = null;
    copy($scratch, $emptyDb);
    foreach (['', '-wal', '-shm'] as $suffix) @unlink($scratch . $suffix);
    echo "Wrote database/schema.sql and database/spence_empty.db\n";
}
